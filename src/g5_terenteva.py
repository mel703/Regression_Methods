"""
Дарья, гипотеза Г5: алкоголь в выходные снижает итоговую оценку.

Признак: Walc — алкоголь в выходные (1 — очень мало ... 5 — очень много).
Способ А: сравниваем среднюю G3 у группы с низким Walc (1–2) и высоким Walc (4–5).

Правило вывода (записано ДО проверки):
    подтверждена, если средняя G3 у группы с высоким Walc (4–5)
    ниже средней G3 у группы с низким Walc (1–2) хотя бы на 1 балл.
"""

from common import compare_groups, load_table

THRESHOLD = 1.0  # баллов

# ---------- Способ А: сравнить группы ----------
# Гипотеза: «алкоголь в выходные снижает оценку».
# Правило вывода: подтверждена, если высокий Walc (4–5) ниже низкого (1–2) хотя бы на 1 балл.

# 1. Таблица «значение Walc -> учеников -> средняя G3» + картинка
table = compare_groups('Walc', name='g5_walc')
print('Способ А — средняя G3 по значениям Walc:')
print(table)

# 2. Объединяем значения в две группы: низкий (1–2) и высокий (4–5)
df = load_table()
mean_low = df[df['Walc'].isin([1, 2])]['G3'].mean()
mean_high = df[df['Walc'].isin([4, 5])]['G3'].mean()
diff = mean_low - mean_high  # насколько высокий Walc ниже

print()
print(f'Низкий Walc (1–2): средняя G3 = {mean_low:.2f}')
print(f'Высокий Walc (4–5): средняя G3 = {mean_high:.2f}')
print(f'Разница (низкий − высокий): {diff:+.2f} балла')
print('Г5:', 'подтверждена' if diff > THRESHOLD else 'опровергнута')

print('\nКартинка: figures/g5_walc.png')