from common import compare_groups, compare_without

# ---------- Способ А: сравнить группы ----------
# Гипотеза (пример): «юноши и девушки учатся одинаково».
# Правило вывода (пишем ДО проверки): подтверждена, если разница средних меньше 1 балла.
table = compare_groups('sex', name='example_a')
print('Способ А — средняя G3 по группам:')
print(table)
diff = table['средняя G3'].max() - table['средняя G3'].min()
print(f'Разница: {diff:.2f} балла ->', 'подтверждена' if diff < 1 else 'опровергнута')

# ---------- Способ Б: убрать признак ----------
# Гипотеза (пример): «детский сад модели не нужен».
# Правило вывода: подтверждена, если без признака ошибка выросла меньше чем на 0,05 балла.
res = compare_without(['nursery'], name='example_b')
print(f'\nСпособ Б — ошибка со всеми признаками: {res["mae_all"]:.3f} балла')
print(f'Ошибка без признака: {res["mae_without"]:.3f} балла')
print(f'Разница: {res["difference"]:+.3f} балла ->',
      'подтверждена' if res['difference'] < 0.05 else 'опровергнута')

print('\nКартинки: figures/example_a.png и figures/example_b.png')
